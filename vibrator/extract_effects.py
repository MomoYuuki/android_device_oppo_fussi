"""Generate fussi's QTI standard effects and experimental composition primitives."""

import argparse
import hashlib
from pathlib import Path
import struct


SOURCE_SHA256 = "b5fe563943546e14a7001f85caee58ceb69bcee9f8346e1c0eace78368db90af"
# Default/832 table used by get_effect_stream() in this exact library revision.
TABLE_ADDRESS = 0x3FB600
TABLE_ENTRIES = 43
DOUBLE_CLICK_GAP_MS = 50
OUTPUT = Path(__file__).resolve().parent / "include" / "VibrationEffectConfig.h"


def read_effects(source):
    data = source.read_bytes()
    if hashlib.sha256(data).hexdigest() != SOURCE_SHA256:
        raise ValueError("Source does not match the verified PEEM00 ColorOS 14.0.0.618 library")

    phoff = struct.unpack_from("<Q", data, 32)[0]
    phsize, phcount = struct.unpack_from("<HH", data, 54)
    segments = []
    for i in range(phcount):
        kind, _, offset, address, _, size, _, _ = struct.unpack_from(
            "<II6Q", data, phoff + i * phsize
        )
        if kind == 1:  # PT_LOAD
            segments.append((address, offset, size))

    def read_address(address, size):
        for start, offset, length in segments:
            if start <= address and address + size <= start + length:
                pos = offset + address - start
                return data[pos : pos + size]
        raise ValueError(f"Unmapped library address: {address:#x}")

    effects = {}
    for i in range(TABLE_ENTRIES):
        effect_id, length, rate, address = struct.unpack(
            "<III4xQ", read_address(TABLE_ADDRESS + i * 24, 24)
        )
        samples = read_address(address, length)
        if effect_id in effects or rate not in (8000, 24000):
            raise ValueError("Unexpected source effect table")
        effects[effect_id] = (rate, samples)
    return effects


def render(effects):
    # This is an Android test mapping, not a claim about ColorOS UI semantics.
    selected = [
        (0, "click", 10),
        (1, "double_click", None),
        (2, "tick", 1),
        (3, "thud", 3),
        (4, "pop", 4),
        (5, "heavy_click", 10),
    ]
    lines = [
        "/*",
        " * Generated by vibrator/extract_effects.py. Do not edit sample data by hand.",
        " * Source: PEEM00 ColorOS 14.0.0.618, odm/lib64/libqtivibratoreffect.so.",
        f" * Source SHA-256: {SOURCE_SHA256}",
        " * Waveform samples are extracted from the original firmware's default/832 table.",
        " * Android effect mapping is experimental; see vibrator/README.md.",
        " */",
        "",
        "#pragma once",
        "",
    ]
    entries = []
    for android_id, name, stock_id in selected:
        if stock_id is None:
            rate, click = effects[10]
            samples = click + bytes(rate * DOUBLE_CLICK_GAP_MS // 1000) + click
            origin = f"Two stock effect 10 pulses, separated by {DOUBLE_CLICK_GAP_MS} ms of silence"
        else:
            rate, samples = effects[stock_id]
            origin = f"Stock effect {stock_id}; original samples and sample rate"
        if not any(samples):
            raise ValueError(f"Silent Android effect: {name}")
        lines += [f"// {origin}.", f"static const int8_t fussi_{name}[] = {{"]
        values = [value if value < 128 else value - 256 for value in samples]
        for start in range(0, len(values), 16):
            lines.append("    " + ", ".join(f"{value:4d}" for value in values[start : start + 16]) + ",")
        lines += ["};", ""]
        entries += [
            f"    // {name.upper()}",
            "    {",
            f"        .effect_id = {android_id},",
            f"        .length = ARRAY_SIZE(fussi_{name}),",
            f"        .play_rate_hz = {rate},",
            f"        .data = fussi_{name},",
            "    },",
        ]
    lines += ["static const struct effect_stream effects[] = {", *entries, "};", ""]

    # Experimental Android semantics, not a recovered ColorOS primitive table.
    # Reuse the tested CLICK/TICK pulses. Other shapes require device validation.
    primitive_sources = [
        (0, "noop", 5, 1),
        (1, "primitive_click", 10, 1),
        (2, "primitive_thud", 3, 1),
        (3, "spin", 12, 1),
        (4, "quick_rise", 6, 1),
        (5, "slow_rise", 8, 1),
        (6, "quick_fall", 7, 1),
        (7, "light_tick", 1, 1),
        (8, "low_tick", 1, 1),
    ]
    entries = []
    for primitive_id, name, stock_id, divisor in primitive_sources:
        rate, samples = effects[stock_id]
        values = [value if value < 128 else value - 256 for value in samples]
        # Round toward zero symmetrically, avoiding a negative DC bias.
        values = [(1 if value >= 0 else -1) * (abs(value) // divisor) for value in values]
        if primitive_id == 0:
            if any(values):
                raise ValueError("NOOP source must be silent")
        elif not any(values):
            raise ValueError(f"Silent primitive: {name}")
        lines += [
            f"// Experimental {name.upper()}: stock {stock_id}, amplitude divisor {divisor}.",
            f"static const int8_t fussi_{name}[] = {{",
        ]
        for start in range(0, len(values), 16):
            lines.append("    " + ", ".join(f"{value:4d}" for value in values[start : start + 16]) + ",")
        lines += ["};", ""]
        entries += [
            f"    // {name.upper()}",
            "    {",
            f"        .effect_id = {primitive_id},",
            f"        .length = ARRAY_SIZE(fussi_{name}),",
            f"        .play_rate_hz = {rate},",
            f"        .data = fussi_{name},",
            "    },",
        ]
    lines += ["static const struct effect_stream primitives[] = {", *entries, "};", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("library", type=Path, help="Original odm/lib64/libqtivibratoreffect.so")
    parser.add_argument("--check", action="store_true", help="Compare without writing files")
    args = parser.parse_args()
    try:
        content = render(read_effects(args.library))
        if args.check:
            if OUTPUT.read_text() != content:
                raise ValueError("Generated header differs from the verified source and mapping")
            print("Source checksum, waveform extraction and generated header match")
        else:
            OUTPUT.parent.mkdir(parents=True, exist_ok=True)
            OUTPUT.write_text(content)
            print(f"Generated {OUTPUT}")
    except (OSError, ValueError, struct.error) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
